// Generates api-server/seed-library.sql from the frontend's own data modules
// (moaz-alian/src/data/…). Run from api-server/:
//   node --experimental-strip-types tools/generate-seed.mjs
// The frontend arrays are the single source of truth; the enum ordinals below mirror
// src/ApiServer.Domain/Enums exactly, so API responses match the frontend types byte-for-byte.
import { register } from "node:module";
register("./seed-hooks.mjs", import.meta.url);

const { categories } = await import("../../moaz-alian/src/data/categories.ts");
const { articles } = await import("../../moaz-alian/src/data/library/articles.ts");
const { books } = await import("../../moaz-alian/src/data/library/books.ts");
const { research } = await import("../../moaz-alian/src/data/library/research.ts");
const { videos } = await import("../../moaz-alian/src/data/library/videos.ts");

const TYPE = { video: 1, book: 2, article: 3, research: 4 };
const RIGHTS = { owned: 1, licensed: 2, external: 3, unknown: 4 };
const AVAILABILITY = { digital: 1, print: 2, unknown: 3 };
const PROVIDER = { youtube: 1 };

const q = (v) => v === null || v === undefined ? "NULL" : `'${String(v).replaceAll("'", "''")}'`;
const json = (v) => q(JSON.stringify(v ?? []));
const stamp = (dateOnly) => dateOnly ? `${String(dateOnly).length === 10 ? `${dateOnly}T00:00:00` : dateOnly}+00:00` : null;

const items = [...videos, ...books, ...articles, ...research];

const lines = [
  "-- Generated by tools/generate-seed.mjs from moaz-alian/src/data — do not edit by hand.",
  "-- Idempotent: re-running refreshes every row in place (upsert), matching the frontend arrays.",
  "",
  "BEGIN;",
  "",
  "TRUNCATE library.content_item_categories;",
  "",
  "INSERT INTO library.categories (\"Id\", \"Name\", \"Description\", \"SortOrder\", \"CreatedAt\", \"UpdatedAt\")",
  "VALUES",
  categories.map((c, i) =>
    `  (${q(c.id)}, ${q(c.name)}, ${q(c.description)}, ${i + 1}, now(), now())`).join(",\n"),
  "ON CONFLICT (\"Id\") DO UPDATE SET",
  '  "Name" = EXCLUDED."Name", "Description" = EXCLUDED."Description",',
  '  "SortOrder" = EXCLUDED."SortOrder", "UpdatedAt" = now();',
  "",
  "INSERT INTO library.content_items",
  '  ("Id", "Type", "Slug", "Title", "Description", "ThumbnailUrl", "AuthorName", "SourceUrl",',
  '   "Tags", "Featured", "Verified", "Demo", "RightsStatus", "PublishedAt", "CreatedAt", "UpdatedAt",',
  '   "VideoId", "VideoProvider", "DurationSeconds", "SeriesName",',
  '   "CoverUrl", "Publisher", "Isbn", "PublicationYear", "Availability", "AuthorizedLinks",',
  '   "Body", "ReadingTimeMinutes", "References", "DocumentUrl", "DocumentFormat")',
  "VALUES",
  items.map((item) => {
    const common = [
      q(item.id), TYPE[item.type], q(item.slug), q(item.title), q(item.description),
      q(item.thumbnailUrl ?? null), q(item.authorName ?? null), q(item.sourceUrl ?? null),
      json(item.tags), item.featured, item.verified, item.demo,
      RIGHTS[item.rightsStatus ?? "unknown"], q(stamp(item.publishedAt ?? null)), "now()", "now()",
    ];
    const perType = item.type === "video"
      ? [q(item.videoId ?? null), item.videoProvider ? PROVIDER[item.videoProvider] : "NULL",
          item.durationSeconds ?? "NULL", q(item.seriesName ?? null)]
      : ["NULL", "NULL", "NULL", "NULL"];
    const bookCols = item.type === "book"
      ? [q(item.coverUrl ?? null), q(item.publisher ?? null), q(item.isbn ?? null),
          item.publicationYear ?? "NULL",
          item.availability ? AVAILABILITY[item.availability] : "NULL",
          // EF's ToJson() deserializes case-sensitively against CLR names (PascalCase);
          // the API responses still surface camelCase via the DTO, matching the frontend.
          q(JSON.stringify((item.authorizedLinks ?? []).map((l) => ({ Label: l.label, Url: l.url })))),
        ]
      : ["NULL", "NULL", "NULL", "NULL", "NULL", "'[]'::jsonb"];
    const docCols = [
      q(item.body ?? null),
      item.readingTimeMinutes ?? "NULL",
      json(item.references ?? []),
      q(item.documentUrl ?? null),
      q(item.documentFormat ?? null),
    ];
    return `  (${[...common, ...perType, ...bookCols, ...docCols].join(", ")})`;
  }).join(",\n"),
  "ON CONFLICT (\"Id\") DO UPDATE SET",
  '  "Type" = EXCLUDED."Type", "Slug" = EXCLUDED."Slug", "Title" = EXCLUDED."Title",',
  '  "Description" = EXCLUDED."Description", "ThumbnailUrl" = EXCLUDED."ThumbnailUrl",',
  '  "AuthorName" = EXCLUDED."AuthorName", "SourceUrl" = EXCLUDED."SourceUrl",',
  '  "Tags" = EXCLUDED."Tags", "Featured" = EXCLUDED."Featured", "Verified" = EXCLUDED."Verified",',
  '  "Demo" = EXCLUDED."Demo", "RightsStatus" = EXCLUDED."RightsStatus",',
  '  "PublishedAt" = EXCLUDED."PublishedAt", "UpdatedAt" = now(),',
  '  "VideoId" = EXCLUDED."VideoId", "VideoProvider" = EXCLUDED."VideoProvider",',
  '  "DurationSeconds" = EXCLUDED."DurationSeconds", "SeriesName" = EXCLUDED."SeriesName",',
  '  "CoverUrl" = EXCLUDED."CoverUrl", "Publisher" = EXCLUDED."Publisher",',
  '  "Isbn" = EXCLUDED."Isbn", "PublicationYear" = EXCLUDED."PublicationYear",',
  '  "Availability" = EXCLUDED."Availability", "AuthorizedLinks" = EXCLUDED."AuthorizedLinks",',
  '  "Body" = EXCLUDED."Body", "ReadingTimeMinutes" = EXCLUDED."ReadingTimeMinutes",',
  '  "References" = EXCLUDED."References", "DocumentUrl" = EXCLUDED."DocumentUrl",',
  '  "DocumentFormat" = EXCLUDED."DocumentFormat";',
  "",
  "INSERT INTO library.content_item_categories (\"CategoriesId\", \"ContentItemsId\")",
  "VALUES",
  items
    .filter((item) => (item.categoryIds ?? []).length > 0)
    .map((item) => item.categoryIds.map((cid) => `  (${q(cid)}, ${q(item.id)})`).join(",\n"))
    .join(",\n"),
  "ON CONFLICT DO NOTHING;",
  "",
  "COMMIT;",
  "",
];

const out = new URL("../seed-library.sql", import.meta.url);
const { writeFileSync } = await import("node:fs");
writeFileSync(out, lines.join("\n"), "utf8");
console.log(`seed-library.sql written: ${categories.length} categories, ${items.length} items (${videos.length} video, ${books.length} book, ${articles.length} article, ${research.length} research)`);
